def set_cell(cell, lines):
    if isinstance(lines, str):
        lines = [lines]
    ps = cell.paragraphs
    tpl = ps[-1]._p if len(ps) > 1 else ps[0]._p        # 여러 줄 셀은 마지막(• 항목) 문단 서식을 씀
    first = copy.deepcopy(ps[0]._p)
    for p in ps:
        p._p.getparent().remove(p._p)
    for i, t in enumerate(lines):
        el = copy.deepcopy(first if i == 0 else tpl)
        cell._tc.append(el)
        p = Paragraph(el, cell)
        rs = p.runs
        for r in rs[1:]:
            r._r.getparent().remove(r._r)
        if rs:
            rs[0].text = t
        else:
            p.add_run(t)


def fill(table, rows):
    """표의 데이터 행을 rows로 교체(행 수가 다르면 마지막 행을 복제·삭제)."""
    body = table.rows[1:]
    tpl = copy.deepcopy(body[-1]._tr)
    for r in body[len(rows):]:
        r._tr.getparent().remove(r._tr)
    while len(table.rows) - 1 < len(rows):
        table._tbl.append(copy.deepcopy(tpl))
    for r, vals in zip(table.rows[1:], rows):
        for c, v in zip(r.cells, vals):
            set_cell(c, v)


def para_after(anchor_el, tpl_par, text):
    el = copy.deepcopy(tpl_par._p)
    anchor_el.addnext(el)
    p = Paragraph(el, tpl_par._parent)
    for r in p.runs[1:]:
        r._r.getparent().remove(r._r)
    p.runs[0].text = text
    return el


